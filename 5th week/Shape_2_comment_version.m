%% 2. 도형끼리 겹치지 않도록 위치를 설정해 주세요. 원 2개, 삼각형 2개, 사각형 2개, 오각형 2개, 육각형 2개를 그리세요.
% 5초마다 사진을 찍어서 저장하세요(타이머가 5초일 때, 10초일 때, 15초일때, ..)

% 우선, 색은 특정 색 하나로 고정하자(랜덤한 한 색 뽑으면 될것같다). 
% 그리고, 도형끼리 겹치지 않기 위해선 그리드 형식을 채택하는게 좋을것 같다. 
% 10개를 그려야 하는데, 각 도형에 해당하는 것을 먼저 저장하자. 
% 그 후 Shape_1에서와 비슷하게 제시하는데 위치에 대한 것을 그리드로 설정하는 코드로 바꾸면 될것 같다.
% 크기는 이전 코드 그대로 옮겨와 사용하자. 
% 스크린샷은 새로운 파일로 5초마다 한장씩, 일단 1분까지만 설정하고 찍자. 


% 기본설정 1: 기존 작업 환경 및 화면 상태를 깨끗하게 초기화합니다.
clear;          % 메모리에 저장된 모든 변수를 삭제하여 충돌을 방지합니다.
clc;            % 명령창(Command Window)의 텍스트를 모두 깨끗하게 지웁니다.
close all;      % 열려 있는 모든 MATLAB 일반 그림(Figure) 창을 닫습니다.
sca;            % Screen('CloseAll')과 동일하며, 열려 있는 모든 PTB 스크린 창을 완전히 닫습니다.

% 기본설정 2: Psychtoolbox 실행을 위한 하드웨어 최적화 및 기본 설정을 적용합니다.
Screen('Preference', 'SkipSyncTests', 1); % 주사율 동기화 테스트를 건너 뛰어 프로그램이 에러 없이 즉시 켜지도록 설정합니다. (디버깅 필수)
PsychDefaultSetup(1);                      % Psychtoolbox의 기본 키보드 매핑 및 내장 설정을 최적화하여 초기화합니다.

try
    % 모니터 및 화면 디스플레이 정보를 가져옵니다.
    screens = Screen('Screens');          % 현재 컴퓨터에 연결된 모든 모니터의 인덱스 배열(번호 목록)을 가져옵니다.
    screenNumber = max(screens);          % 듀얼 모니터일 경우 보조 모니터(가장 큰 숫자)를, 싱글이면 주 모니터(0)를 선택합니다.
    white = WhiteIndex(screenNumber);     % 해당 모니터에서 사용할 수 있는 가장 밝은 '흰색'의 코드값(보통 255)을 가져옵니다.
    black = BlackIndex(screenNumber);     % 해당 모니터에서 사용할 수 있는 가장 어두운 '검은색'의 코드값(보통 0)을 가져옵니다.
    gray = white / 2;                     % 흰색 코드의 절반 값을 계산하여 배경색으로 사용할 균일한 '회색' 값을 만듭니다.

    % 실험창(윈도우)을 열고 알파 블렌딩 설정을 적용합니다.
    [window, windowRect] = Screen('OpenWindow', screenNumber, gray); % 지정한 모니터에 회색 배경의 전체 화면 창을 열고, 창 ID(window)와 해상도 크기(windowRect)를 받습니다.
    Screen('BlendFunction', window, 'GL_SRC_ALPHA', 'GL_ONE_MINUS_SRC_ALPHA'); % 투명도(Alpha 채널) 및 안티앨리어싱(부드러운 선 처리)이 가능하도록 그래픽 블렌딩 모드를 활성화합니다.
    Screen('Flip', window);               % 빈 회색 화면을 모니터 실제 화면에 적용하여 첫 화면을 깨끗하게 출력합니다.

    % 도형들이 절대 겹치지 않도록 화면을 4x4 격자(총 16개 방)로 나누기 위한 중심 좌표들을 생성합니다.
    gridX = linspace(windowRect(3) * 0.1, windowRect(3) * 0.9, 4); % 화면 전체 가로 폭의 10% 지점부터 90% 지점까지 4개의 X 좌표를 등간격으로 생성합니다.
    gridY = linspace(windowRect(4) * 0.2, windowRect(4) * 0.8, 4); % 화면 전체 세로 폭의 20% 지점부터 80% 지점까지 4개의 Y 좌표를 등간격으로 생성합니다.
    [X, Y] = meshgrid(gridX, gridY);      % 4개의 X좌표와 4개의 Y좌표를 직교 조합하여 4x4 격자 형태의 평면 좌표망을 형성합니다.
    allRooms = [X(:), Y(:)];              % 4x4 행렬 좌표 구조를 일렬로 풀어서 총 16행 2열(1열: X중심좌표, 2열: Y중심좌표) 형태의 배치 가능 목록으로 변환합니다.

    % [요구사항] 그릴 도형 10개의 종류를 미리 정의합니다. (원 2개, 사각형 2개, 삼각형 2개, 오각형 2개, 육각형 2개)
    % 0은 원(꼭짓점 무한대 대체), 3은 삼각형, 4는 사각형, 5는 오각형, 6은 육각형의 꼭짓점 개수를 의미합니다.
    ShapeTypes =; 

    % 10개 도형이 들어갈 가상의 격자 방을 중복 없이 고르고 크기와 고정 색상을 설정합니다.
    chosenRooms = allRooms(randperm(16, 10), :); % 1부터 16까지 무작위 순열을 만든 후 앞의 10개만 선택하여, 도형들이 서로 절대 겹치지 않게 10개의 중심 좌표를 비복원 추출합니다.
    sz = double(randi([50, 100], 10, 1));        % 각 도형의 외접원 지름 역할을 할 크기(50~100 픽셀 사이의 무작위 정수)를 10행 1열 구조의 정밀한 실수 데이터로 생성합니다.
    singleColor = randi([0 255], 3, 1);          % [요구사항] 모든 도형에 동일하게 적용할 하나의 무작위 고정 RGB 색상 [R; G; B]을 3행 1열 구조로 추출합니다.

    % [디버깅 안전장치] 백그라운드 키보드 입력 감지 기능을 활성화합니다.
    KbQueueCreate;                        % 비동기 키 입력 감지를 위한 독립적인 메모리 공간(큐)을 백그라운드에 할당합니다.
    KbQueueStart;                         % 실시간 키보드 입력 모니터링을 실제로 개시합니다.

    % [요구사항] 5초마다 사진을 찍으며 일단 1분(60초)까지만 설정하고 타이머 루프를 실행합니다.
    for timer = 1:60                      % 1초에 한 번씩 숫자가 올라가며 총 60초(1분) 동안 진행되는 메인 루프입니다.
        
        % 화면 버퍼에 10개의 다각형 도형을 순서대로 미리 그리는 루프입니다.
        for i = 1:10                      % 저장해 둔 10개의 도형 데이터를 하나씩 순회하며 그리는 내부 루프입니다.
            n = ShapeTypes(i);            % 현재 i번째 차례에서 그려야 할 도형의 고유 꼭짓점 개수(변의 수)를 배열에서 가져옵니다.
            if n == 0                     % 만약 꼭짓점 개수가 0(원으로 정의된 값)이라면
                n = 360;                  % 삼각함수로 원을 표현하기 위해 꼭짓점 개수를 360개로 변환하여 원형태로 둥글게 보이게 만듭니다.
            end
            r = sz(i) / 2;                % 도형의 외접원 반지름을 구하기 위해 무작위로 지정되었던 크기(지름) 값을 2로 나눕니다.
            cx = chosenRooms(i, 1);       % 겹치지 않게 선점된 10개의 방 좌표 중 i번째 방의 X축 중심 좌표를 가져옵니다.
            cy = chosenRooms(i, 2);       % 겹치지 않게 선점된 10개의 방 좌표 중 i번째 방의 Y축 중심 좌표를 가져옵니다.
            
            % 극좌표계 원리를 활용하여 중심점으로부터 일정한 각도로 벌어진 다각형의 꼭짓점 각도들을 계산합니다.
            theta = linspace(0, 2*pi, n+1)'; % 0라디안(0도)부터 2*pi라디안(360도)까지의 범위를 꼭짓점 개수 + 1만큼 균일하게 쪼갠 후 세로 벡터(')로 정렬합니다. (+1을 하는 이유는 시작점과 끝점이 만나 도형이 닫히게 하기 위함입니다.)
            
            % 삼각함수의 공식(X = 중심 + 반지름*cos, Y = 중심 + 반지름*sin)을 사용하여 각 꼭짓점의 2차원 평면 좌표를 계산합니다.
            every_points = [cx + r*cos(theta), cy + r*sin(theta)]; % 계산된 꼭짓점들의 X좌표(1열)와 Y좌표(2열)를 결합하여 다각형의 전체 외곽선 좌표 행렬을 생성합니다.

            % 계산된 꼭짓점 좌표 목록들을 연결하여 지정된 고정 색상으로 채워진 다각형을 메모리 버퍼 화면에 그립니다.
            Screen('FillPoly', window, singleColor, every_points);
        end % 10개 도형 그리기 내부 루프 종료

        % 경과 시간을 나타내는 안내 텍스트를 생성하고 배치합니다.
        infoText = sprintf('Time Passed: %ds / 60s\n\n[Press ESC to Quit]', timer); % 현재 경과 시간과 전체 제한시간, 그리고 강제종료 단축키 안내를 문자열로 결합합니다.
        DrawFormattedText(window, infoText, 50, 50, white); % 지정된 윈도우 창의 좌측 상단(X=50, Y=50) 좌표에 흰색 글씨로 텍스트를 렌더링합니다.

        % 가상 버퍼에 그려진 10개의 도형과 경과 시간 텍스트를 모니터의 실제 화면으로 반전시켜 출력(적용)합니다.
        Screen('Flip', window);

        % [요구사항] 5초마다 사진을 찍어서 현재 매틀랩 작업 폴더에 저장하는 스크린샷 로직입니다.
        if mod(timer, 5) == 0             % 현재 타이머 초를 5로 나눈 나머지 값이 0일 때 (즉 5초, 10초, 15초... 일 때만 참이 됩니다.)
            imageArray = Screen('GetImage', window); % 현재 실제 모니터 화면에 표출되고 있는 윈도우 창의 그래픽 픽셀 데이터를 RGB 행렬 배열로 캡처하여 가져옵니다.

            filename = sprintf('screenshot_%ds.png', timer); % 저장될 이미지의 파일명을 'screenshot_5s.png', 'screenshot_10s.png' 등 시간별로 고유하게 생성합니다.
            imwrite(imageArray, filename); % 캡처한 픽셀 데이터(imageArray)를 PNG 포맷의 이미지 파일로 현재 컴퓨터 디렉토리에 물리적으로 저장합니다.
        end % 스크린샷 조건문 종료
        
        % 1초 동안 프로그램 흐름을 멈추고 대기합니다.
        WaitSecs(1);

        % [디버깅 안전장치 작동] 1초 대기 직후 백그라운드 큐에 저장된 ESC 키 입력을 확인하여 강제 탈출을 실행합니다.
        [pressed, firstPress] = KbQueueCheck; % 대기하는 시간 동안 사용자가 키를 눌렀었는지 여부와 키별 입력 타이밍 배열을 반환받습니다.
        if pressed && firstPress(KbName('ESCAPE')) % 키가 눌렸고, 그 키의 식별자가 ESC 키라면 조건문 내부를 실행합니다.
                error('사용자가 ESC를 눌러 종료했습니다.') % 의도적인 런타임 에러를 발생시켜 실행을 즉시 중단하고 하단의 catch 블록으로 점프하게 만듭니다.
        end
    end % 60초 타이머 메인 루프 종료


    % 모든 타이머와 1분 실험이 정상적으로 마무리되었을 때의 리소스 정리 단계입니다.
    KbQueueRelease;                       % 백그라운드 키보드 입력 감지 큐를 완전히 닫고 메모리를 해제합니다.
    sca;                                  % 실험용 창을 완전히 닫고 모니터 해상도를 원래의 컴퓨터 환경으로 안전하게 복구합니다.
    ShowCursor;                           % 실험을 위해 일시적으로 숨겨두었던 마우스 커서를 화면에 다시 표출시킵니다.
    disp('Experiment successfully finished'); % MATLAB 명령창(Command Window)에 성공적인 종료 안내 문구를 출력합니다.

catch info
    % try 블록 내부에서 에러가 발생하거나 사용자가 ESC 키를 눌러 강제 오류를 유도했을 때 실행되는 비상 복구 영역입니다.
    KbQueueRelease;                       % 시스템이 비정상 종료되더라도 키보드 감지 장치가 메모리에 남아 먹통을 유발하지 않도록 확실하게 해제합니다.
    sca;                                  % 전체화면 창이 그대로 굳어 매틀랩 제어권을 잃어버리는 현상을 막기 위해 강제로 창을 파괴합니다.
    ShowCursor;                           % 숨겨졌던 마우스 커서를 원래대로 복원합니다.
    rethrow(info);                        % 매틀랩 명령창에 원래 발생했던 에러 객체(에러 원인 및 발생 행 번호 정보 등)를 그대로 뿌려주어 디버깅을 돕습니다.
end